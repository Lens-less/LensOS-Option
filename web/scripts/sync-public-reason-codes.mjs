import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const webDir = resolve(here, "..");
const catalogPath = resolve(webDir, "src", "reasonCodes", "catalog.json");
const outputPath = resolve(
  webDir,
  "src",
  "public",
  "publicReasonCodes.generated.ts",
);

const catalog = JSON.parse(readFileSync(catalogPath, "utf8"));

const entries = Object.entries(catalog).flatMap(([code, entry]) =>
  entry.public
    ? [`  ${code}: ${JSON.stringify(entry.public, null, 2).replace(/\n/g, "\n  ")},`]
    : [],
);

const output = `// Generated by npm run sync:public-reason-codes. Do not edit by hand.
export interface PublicReasonCodeReading {
  title: string;
  detail: string;
}

export const PUBLIC_REASON_CODE_READINGS: Record<string, PublicReasonCodeReading> = {
${entries.join("\n")}
};
`;

writeFileSync(outputPath, output, "utf8");
